#!/usr/bin/env python3
"""Generate a PyMOL script per docked structure to visualize the results.

For every data/output/vina_poses/<base_name>_vina_output.pdbqt, finds the
matching original receptor (data/input/<base_name>.pdb, or
data/intermediate/relaxed/<base_name>.pdb for relaxed models) and writes a
.pml script to data/output/pymol_scripts/<base_name>_view.pml that:
  - loads the receptor as cartoon, with the P-loop motif residues (from
    data/intermediate/motif_residues.json) shown as sticks, highlighted, and
    labeled (3-letter residue code at each CA)
  - loads the Vina output poses (each mode becomes a PyMOL state) as sticks
  - draws polar contacts (`distance ..., mode=2`) between the poses and the
    receptor, colored separately for contacts to P-loop residues vs. to the
    rest of the receptor
  - if a matching data/intermediate/vina_configs/<base_name>_config.txt
    exists, overlays the docking search box via scratch/docking_box.py

Paths inside the generated scripts are relative to the repo root (same
convention as the Vina configs), so run PyMOL from the repo root, e.g.
`pymol data/output/pymol_scripts/<base_name>_view.pml`.
"""
import argparse
import re
from pathlib import Path

from paths import (
    INPUT_DIR, RELAXED_DIR, VINA_CONFIGS_DIR, VINA_POSES_DIR,
    PYMOL_SCRIPTS_DIR, DOCKING_BOX_SCRIPT, MOTIF_RESIDUES_FILE, rel,
)
from pdb_utils import load_motif_residues

BOX_KEYS = ("center_x", "center_y", "center_z", "size_x", "size_y", "size_z")
BACKGROUND_COLOR = "black"
RECEPTOR_COLOR = "skyblue"
# Not orange -- that's PyMOL's default element color for phosphorus, which
# would blend the P-loop sticks into ATP's phosphate tail.
PLOOP_COLOR = "magenta"
PLOOP_LABEL_COLOR = "white"
PLOOP_HBOND_COLOR = "yellow"
OTHER_HBOND_COLOR = "cyan"
HBOND_DASH_TRANSPARENCY = 0.5


def motif_resi_selection(motif_residues):
    """PyMOL `resi` selection string, e.g. "9-16+62-69", from [start, end] ranges."""
    return "+".join(f"{start}-{end}" for start, end in motif_residues)


def find_receptor(base_name):
    for candidate_dir in (INPUT_DIR, RELAXED_DIR):
        candidate = candidate_dir / f"{base_name}.pdb"
        if candidate.exists():
            return candidate
    return None


def parse_vina_config(config_path):
    """key -> value for the "key = value" lines in a Vina config file."""
    values = {}
    for line in config_path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def load_box_params(base_name, configs_dir):
    config_path = configs_dir / f"{base_name}_config.txt"
    if not config_path.exists():
        return None
    values = parse_vina_config(config_path)
    if not all(key in values for key in BOX_KEYS):
        print(f"  WARNING: {config_path} is missing box parameters, skipping box overlay")
        return None
    return {key: float(values[key]) for key in BOX_KEYS}


def write_pymol_script(
    script_path, receptor_path, poses_path, box_params, docking_box_script, motif_selection,
    show_hbonds=True,
):
    lines = [
        "# Auto-generated by 05_generate_pymol_scripts.py -- do not edit by hand.",
        f"load {rel(receptor_path)}, receptor",
        f"load {rel(poses_path)}, poses",
        "",
        "hide everything",
        f"bg_color {BACKGROUND_COLOR}",
        "show cartoon, receptor",
        f"color {RECEPTOR_COLOR}, receptor",
        "",
    ]
    if motif_selection:
        lines += [
            f"select ploop, receptor and resi {motif_selection}",
            "show sticks, ploop",
            f"color {PLOOP_COLOR}, ploop and elem C",
            "label ploop and name CA, resn",
            f"set label_color, {PLOOP_LABEL_COLOR}",
            "set label_size, 10",
            "",
        ]
    lines += [
        "show sticks, poses",
        "util.cbag poses",
        "",
    ]
    if show_hbonds:
        if motif_selection:
            lines += [
                f"distance hbonds_ploop, poses, receptor and resi {motif_selection}, mode=2",
                f"color {PLOOP_HBOND_COLOR}, hbonds_ploop",
                f"set dash_transparency, {HBOND_DASH_TRANSPARENCY}, hbonds_ploop",
                f"distance hbonds_other, poses, receptor and not resi {motif_selection}, mode=2",
                f"color {OTHER_HBOND_COLOR}, hbonds_other",
                f"set dash_transparency, {HBOND_DASH_TRANSPARENCY}, hbonds_other",
                "",
            ]
        else:
            lines += [
                "distance hbonds, poses, receptor, mode=2",
                f"color {PLOOP_HBOND_COLOR}, hbonds",
                f"set dash_transparency, {HBOND_DASH_TRANSPARENCY}, hbonds",
                "",
            ]
    if box_params is not None:
        lines += [
            f"run {rel(docking_box_script)}",
            "docking_box name=search_box, "
            + ", ".join(f"{key}={box_params[key]}" for key in BOX_KEYS),
            "",
        ]
    lines += ["zoom receptor"]

    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--vina-poses-dir", type=Path, default=VINA_POSES_DIR)
    parser.add_argument("--vina-configs-dir", type=Path, default=VINA_CONFIGS_DIR)
    parser.add_argument("--output-dir", type=Path, default=PYMOL_SCRIPTS_DIR)
    parser.add_argument("--docking-box-script", type=Path, default=DOCKING_BOX_SCRIPT)
    parser.add_argument("--no-box", action="store_true", help="Never overlay the docking search box")
    parser.add_argument("--motif-residues", type=Path, default=MOTIF_RESIDUES_FILE)
    parser.add_argument(
        "--no-motif", action="store_true", help="Never highlight the P-loop motif residues"
    )
    parser.add_argument(
        "--no-hbonds", action="store_true",
        help="Never draw polar contacts (distance mode=2) between poses and receptor",
    )
    args = parser.parse_args()

    pose_files = sorted(args.vina_poses_dir.glob("*_vina_output.pdbqt"))
    if not pose_files:
        raise SystemExit(
            f"No *_vina_output.pdbqt files in {args.vina_poses_dir} -- run 04_run_docking.sh first"
        )
    print(f"Found {len(pose_files)} docked structures\n")

    motif_selection = None
    if not args.no_motif:
        if args.motif_residues.exists():
            motif_selection = motif_resi_selection(load_motif_residues(args.motif_residues))
        else:
            print(f"WARNING: {args.motif_residues} not found, skipping motif highlighting\n")

    for poses_path in pose_files:
        base_name = re.sub(r"_vina_output$", "", poses_path.stem)
        print(f"Processing {base_name}")

        receptor_path = find_receptor(base_name)
        if receptor_path is None:
            print(f"  WARNING: no receptor PDB found for {base_name}, skipping\n")
            continue

        box_params = None if args.no_box else load_box_params(base_name, args.vina_configs_dir)

        script_path = args.output_dir / f"{base_name}_view.pml"
        write_pymol_script(
            script_path, receptor_path, poses_path, box_params, args.docking_box_script,
            motif_selection, show_hbonds=not args.no_hbonds,
        )
        print(f"  Wrote {script_path}\n")

    print("Done.")


if __name__ == "__main__":
    main()
